// Builds packages/acme/tokens/*.json (DTCG) into dist/tokens.css and dist/tokens.ts.
import StyleDictionary from 'style-dictionary';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// Nested TS map: tokens.color.action.primary.bg === 'var(--color-action-primary-bg)'.
// Raw values are exported separately as `values` for tooling (linters, docs).
StyleDictionary.registerFormat({
  name: 'typescript/acme-map',
  format: ({ dictionary }) => {
    const vars = {};
    const values = {};
    for (const t of dictionary.allTokens) {
      let v = vars;
      let r = values;
      t.path.forEach((seg, i) => {
        if (i === t.path.length - 1) {
          v[seg] = `var(--${t.name})`;
          r[seg] = t.$value ?? t.value;
        } else {
          v = v[seg] ??= {};
          r = r[seg] ??= {};
        }
      });
    }
    return [
      '// Generated by scripts/build-tokens.mjs. Do not edit.',
      `export const tokens = ${JSON.stringify(vars, null, 2)} as const;`,
      `export const values = ${JSON.stringify(values, null, 2)} as const;`,
      'export type AcmeTokens = typeof tokens;',
      '',
    ].join('\n');
  },
});

const sd = new StyleDictionary({
  usesDtcg: true,
  source: [resolve(root, 'tokens/*.json')],
  log: { verbosity: 'default' },
  platforms: {
    css: {
      transformGroup: 'css',
      buildPath: resolve(root, 'dist') + '/',
      files: [
        {
          destination: 'tokens.css',
          format: 'css/variables',
          options: { outputReferences: true },
        },
      ],
    },
    ts: {
      transformGroup: 'css',
      buildPath: resolve(root, 'dist') + '/',
      files: [{ destination: 'tokens.ts', format: 'typescript/acme-map' }],
    },
  },
});

await sd.buildAllPlatforms();
